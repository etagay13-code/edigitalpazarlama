import pg from "pg";
import { writeFileSync } from "node:fs";
const c=new pg.Client({connectionString:process.env.DATABASE_URL,ssl:{rejectUnauthorized:false}});
await c.connect();
const q=async(sql)=> (await c.query(sql)).rows;
const data={};
data.services=await q("select slug,title,short,description,long_description,hero,approach,bullets,deliverables,tools,outcomes,ideal_for from services where locale='tr' order by sort_order");
data.service_process_steps=await q("select s.slug, p.step_number, p.title, p.description from service_process_steps p join services s on s.id=p.service_id and s.locale='tr' order by s.slug, p.step_number");
data.service_faqs=await q("select s.slug, f.question, f.answer, f.sort_order from service_faqs f join services s on s.id=f.service_id and s.locale='tr' order by s.slug, f.sort_order");
data.portfolio_projects=await q("select slug,title,client,description,metric,tags from portfolio_projects where locale='tr' order by sort_order");
data.testimonials=await q("select name,role,company,quote,sort_order from testimonials where locale='tr' order by sort_order");
data.team_members=await q("select name,role,bio,sort_order from team_members where locale='tr' order by sort_order");
data.timeline_events=await q("select year,title,description,sort_order from timeline_events where locale='tr' order by sort_order");
data.industries=await q("select name,description,highlights,sort_order from industries where locale='tr' order by sort_order");
data.tech_items=await q("select name,category,sort_order from tech_items where locale='tr' order by sort_order");
data.faqs=await q("select scope,question,answer,sort_order from faqs where locale='tr' order by scope,sort_order");
data.page_sections=await q("select page_slug,section_key,eyebrow,title,description,body,sort_order from page_sections where locale='tr' order by page_slug,sort_order");
writeFileSync("scripts/i18n/tr.json", JSON.stringify(data,null,2));
const txt=JSON.stringify(data);
console.log("rows:", Object.fromEntries(Object.entries(data).map(([k,v])=>[k,v.length])));
console.log("total chars:", txt.length);
await c.end();
